import fs from 'node:fs';
import assert from 'node:assert/strict';
const source = fs.readFileSync('astra/AI/BrowserAIPageText.swift', 'utf8');
const script = source.split('static let extractionScript = #"""')[1].split('"""#')[0];
const AsyncFunction = Object.getPrototypeOf(async function () {}).constructor;
const run = new AsyncFunction('document', 'location', 'performance', script);
let styleReads = 0;
const ownerDocument = { defaultView: { getComputedStyle() { styleReads++; return {}; } } };
const element = (tagName, childNodes = []) => ({ nodeType: 1, tagName, childNodes, ownerDocument, hidden: false, getAttribute() { return null; }, closest() { return null; } });
const text = nodeValue => ({ nodeType: 3, nodeValue, childNodes: [] });
const document = { title: 'Test', body: element('MAIN', [text('Visible text'), element('INPUT', [text('private form')]), element('SCRIPT', [text('excluded script')])]) };
let result = await run(document, { href: 'https://example.com' }, performance);
assert.equal(result.text, 'Visible text');
document.body = element('MAIN', [text('x'.repeat(10_000_000))]);
result = await run(document, { href: 'https://example.com' }, performance);
assert.ok(result.text.startsWith('x'.repeat(119999)));
assert.ok(result.text.length < 120200 && result.text.includes('excerpt truncated'));
styleReads = 0;
document.body = element('MAIN', Array.from({ length: 40000 }, () => element('SPAN')));
result = await run(document, { href: 'https://example.com' }, performance);
assert.ok(styleReads <= 30000 && result.text.includes('excerpt truncated'));
let shadow = element('DIV'); shadow.shadowRoot = { nodeType: 11, childNodes: [text('shadow')] };
let frame = element('IFRAME'); frame.contentDocument = { body: element('MAIN', [text('frame')]) };
document.body = element('MAIN', [shadow, frame]);
result = await run(document, { href: 'https://example.com' }, performance);
assert.match(result.text, /shadow/); assert.match(result.text, /frame/);
console.log('Page extraction preserves shadow/frame text and enforces node and character budgets');
